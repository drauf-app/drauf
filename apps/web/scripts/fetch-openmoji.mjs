/**
 * Downloads the OpenMoji color SVGs for every icon the catalogue uses into
 * public/openmoji/ and regenerates src/lib/openmoji-manifest.ts. Run after
 * adding catalogue items with new icons:
 *
 *   node scripts/fetch-openmoji.mjs
 *
 * OpenMoji (https://openmoji.org) is licensed CC BY-SA 4.0 — the same license
 * as the catalogue. Assets are committed, so builds never need the network.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OPENMOJI_VERSION = '15.1.0';
const BASE = `https://raw.githubusercontent.com/hfg-gmuend/openmoji/${OPENMOJI_VERSION}/color/svg`;

const webRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(webRoot, '..', '..', 'packages', 'catalog', 'data');
const outDir = join(webRoot, 'public', 'openmoji');
mkdirSync(outDir, { recursive: true });

/** OpenMoji file names: codepoints joined by '-', without variation selectors. */
export function emojiToHex(emoji) {
  return [...emoji]
    .map((char) => char.codePointAt(0))
    .filter((code) => code !== 0xfe0f)
    .map((code) => code.toString(16).toUpperCase())
    .join('-');
}

const icons = new Set();
for (const file of readdirSync(dataDir)) {
  if (!file.endsWith('.json')) continue;
  for (const item of JSON.parse(readFileSync(join(dataDir, file), 'utf8'))) {
    if (typeof item.icon === 'string' && item.icon !== '') {
      icons.add(item.icon);
    }
  }
}

const available = [];
for (const icon of [...icons].sort()) {
  const hex = emojiToHex(icon);
  const target = join(outDir, `${hex}.svg`);
  if (!existsSync(target)) {
    const response = await fetch(`${BASE}/${hex}.svg`);
    if (!response.ok) {
      console.warn(`missing in OpenMoji: ${icon} (${hex}) — keeps the text emoji`);
      continue;
    }
    writeFileSync(target, Buffer.from(await response.arrayBuffer()));
  }
  available.push(hex);
}

const manifest = `// Generated by scripts/fetch-openmoji.mjs — do not edit by hand.
// OpenMoji ${OPENMOJI_VERSION} (https://openmoji.org), CC BY-SA 4.0.
export const OPENMOJI_HEXES: ReadonlySet<string> = new Set([
${available.map((hex) => `  '${hex}',`).join('\n')}
]);
`;
writeFileSync(join(webRoot, 'src', 'lib', 'openmoji-manifest.ts'), manifest);
console.log(`openmoji assets: ${available.length}/${icons.size} icons available`);
