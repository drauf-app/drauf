/**
 * Regenerates src/lib/icon-keywords.ts: German search keywords per bundled
 * icon (#85), seeded from the catalogue's item names and synonyms — the
 * catalogue already maps items to icons, so it knows what each icon means.
 * Run after catalogue changes:
 *
 *   node scripts/build-icon-keywords.mjs
 *
 * The map is committed like openmoji-manifest.ts, so builds never read the
 * catalogue package at runtime.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { emojiToHex } from './icon-set.mjs';

const webRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(webRoot, '..', '..', 'packages', 'catalog', 'data');

/** hex -> Set of lowercase keywords. */
const keywords = new Map();

function add(icon, words) {
  const hex = emojiToHex(icon);
  const set = keywords.get(hex) ?? new Set();
  for (const word of words) {
    const trimmed = word.trim().toLowerCase();
    if (trimmed !== '') {
      set.add(trimmed);
    }
  }
  keywords.set(hex, set);
}

for (const file of readdirSync(dataDir).sort()) {
  if (!file.endsWith('.json')) {
    continue;
  }
  const items = JSON.parse(readFileSync(join(dataDir, file), 'utf8'));
  for (const item of items) {
    if (typeof item.icon !== 'string' || item.icon === '') {
      continue;
    }
    add(item.icon, [item.name, ...(item.synonyms ?? [])]);
  }
}

const entries = [...keywords.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([hex, words]) => `  ['${hex}', '${[...words].sort().join(' ')}'],`)
  .join('\n');

const output = `// Generated by scripts/build-icon-keywords.mjs — do not edit by hand.
// German keywords per bundled icon, seeded from the catalogue (#85).
export const ICON_KEYWORDS: ReadonlyMap<string, string> = new Map([
${entries}
]);
`;

writeFileSync(join(webRoot, 'src', 'lib', 'icon-keywords.ts'), output);
console.log(`icon-keywords.ts: ${keywords.size} icons`);
