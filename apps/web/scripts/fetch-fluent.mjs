/**
 * Downloads the Fluent Emoji Color SVGs for every icon the catalogue uses
 * into public/fluent/ and regenerates src/lib/fluent-manifest.ts. Run after
 * adding catalogue items with new icons:
 *
 *   node scripts/fetch-fluent.mjs
 *
 * Fluent Emoji (https://github.com/microsoft/fluentui-emoji) is MIT-licensed.
 * Assets are committed, so builds never need the network. The repository has
 * no releases, so a commit is pinned; folders map to emoji via each asset's
 * metadata.json ("unicode"), which the script resolves from one tree listing
 * plus small raw fetches.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { collectIcons, emojiToHex } from './icon-set.mjs';

// microsoft/fluentui-emoji main as of 2026-08-24.
const FLUENT_COMMIT = '1ffb34c752ecf5d402f04cfb4b392c77f57c54bc';
const RAW = `https://raw.githubusercontent.com/microsoft/fluentui-emoji/${FLUENT_COMMIT}`;
const TREE = `https://api.github.com/repos/microsoft/fluentui-emoji/git/trees/${FLUENT_COMMIT}?recursive=1`;

const webRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(webRoot, '..', '..', 'packages', 'catalog', 'data');
const outDir = join(webRoot, 'public', 'fluent');
mkdirSync(outDir, { recursive: true });

/** Fluent metadata "unicode" ("1f345", "2744 fe0f") → our hex key ("1F345"). */
function unicodeToHex(unicode) {
  return unicode
    .split(' ')
    .map((part) => part.toUpperCase())
    .filter((part) => part !== 'FE0F')
    .join('-');
}

const icons = collectIcons(dataDir);
const neededHexes = new Set([...icons].map((icon) => emojiToHex(icon)));

async function fetchOk(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url}: HTTP ${response.status}`);
  }
  return response;
}

console.log('listing the pinned fluentui-emoji tree …');
const tree = (await (await fetchOk(TREE)).json()).tree;
const folders = new Set();
const colorSvgByFolder = new Map(); // folder → repo path of its Color SVG
for (const entry of tree) {
  const match = /^assets\/([^/]+)\/(?:Default\/)?Color\/[^/]+\.svg$/.exec(entry.path);
  if (match !== null && !colorSvgByFolder.has(match[1])) {
    colorSvgByFolder.set(match[1], entry.path);
  }
  const meta = /^assets\/([^/]+)\/metadata\.json$/.exec(entry.path);
  if (meta !== null) {
    folders.add(meta[1]);
  }
}
console.log(`${folders.size} asset folders, resolving metadata …`);

/** hex key → repo path of the Color SVG, built from every folder's metadata. */
const pathByHex = new Map();
const queue = [...folders];
const CONCURRENCY = 24;
async function worker() {
  for (let folder = queue.pop(); folder !== undefined; folder = queue.pop()) {
    const metadata = await (
      await fetchOk(`${RAW}/assets/${encodeURIComponent(folder)}/metadata.json`)
    ).json();
    if (typeof metadata.unicode !== 'string') continue;
    const hex = unicodeToHex(metadata.unicode);
    const svgPath = colorSvgByFolder.get(folder);
    if (neededHexes.has(hex) && svgPath !== undefined && !pathByHex.has(hex)) {
      pathByHex.set(hex, svgPath);
    }
  }
}
await Promise.all(Array.from({ length: CONCURRENCY }, worker));

const available = [];
for (const icon of [...icons].sort()) {
  const hex = emojiToHex(icon);
  const target = join(outDir, `${hex}.svg`);
  if (!existsSync(target)) {
    const svgPath = pathByHex.get(hex);
    if (svgPath === undefined) {
      console.warn(`missing in Fluent Emoji: ${icon} (${hex}) — falls back to OpenMoji`);
      continue;
    }
    const svg = Buffer.from(
      await (
        await fetchOk(`${RAW}/${svgPath.split('/').map(encodeURIComponent).join('/')}`)
      ).arrayBuffer(),
    );
    writeFileSync(target, svg);
  }
  available.push(hex);
}

if (!existsSync(join(outDir, 'LICENSE.txt'))) {
  const license = await (await fetchOk(`${RAW}/LICENSE`)).text();
  writeFileSync(join(outDir, 'LICENSE.txt'), license);
}

const manifest = `// Generated by scripts/fetch-fluent.mjs — do not edit by hand.
// Fluent Emoji (https://github.com/microsoft/fluentui-emoji), MIT.
export const FLUENT_HEXES: ReadonlySet<string> = new Set([
${available.map((hex) => `  '${hex}',`).join('\n')}
]);
`;
writeFileSync(join(webRoot, 'src', 'lib', 'fluent-manifest.ts'), manifest);
console.log(`fluent assets: ${available.length}/${icons.size} icons available`);
